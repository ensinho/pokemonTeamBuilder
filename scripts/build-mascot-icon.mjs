// Writes src/utils/mascot/icon.js: the mascot at rest, as static markup, for
// the moments before the rig chunk arrives (the boot splash, the first paint
// of a tip). `icon.test.js` fails when it drifts from the rig — rerun this.
//   node scripts/build-mascot-icon.mjs
import { writeFileSync } from 'node:fs';
import { mascotInner, VIEWS } from '../src/utils/mascot/rig.js';
import { sizeTraits } from '../src/utils/mascot/catalog.js';

const big = mascotInner({});
const small = mascotInner(sizeTraits(24));
const out = `/* Generated by scripts/build-mascot-icon.mjs — do not edit by hand. */
// The mascot at rest (the icon's pose), drawn before the rig chunk loads.
export const ICON_VIEW = '${VIEWS.head}';
export const ICON_INNER = ${JSON.stringify(big)};
// The same at 24 px and below: thicker stroke, no blush or fangs.
export const ICON_INNER_SMALL = ${JSON.stringify(small)};
`;
writeFileSync(new URL('../src/utils/mascot/icon.js', import.meta.url), out);
console.log('icon.js', big.length, 'B /', small.length, 'B');
