// Writes the mascot as an open-bot-avatar definition (2026-11-11):
//   src/utils/mascot/bot/definition.js  — what the app draws
//   public/mascot-bot.json              — the same, for the open-bot-avatar editor's Import
// The geometry is `scripts/lib/mascotBot.mjs`; `bot.test.js` fails when the rig
// changes and this was not rerun.
//   npm run mascot:bot
import { writeFileSync } from 'node:fs';
import { validateAvatar } from '../src/vendor/open-bot-avatar/validate.js';
import { buildBotDefinition } from './lib/mascotBot.mjs';

const { definition, RIG_TO_BOX, RIG_SCALE, K, subpaths } = buildBotDefinition();
const res = validateAvatar(definition);
if (!res.ok) {
    console.error(res.errors.join('\n'));
    process.exit(1);
}
const out = `/* Generated by scripts/build-mascot-bot.mjs — do not edit by hand. */
// The mascot as an open-bot-avatar v1 definition (docs/modules/mascot.md → "The bot").
export const BOT_DEFINITION = ${JSON.stringify(definition, null, 4)};
// Rig space → the definition's 0 0 100 100 box (the icon's tilt included).
export const RIG_TO_BOX = '${RIG_TO_BOX}';
export const RIG_SCALE = ${RIG_SCALE};
`;
writeFileSync(new URL('../src/utils/mascot/bot/definition.js', import.meta.url), out);
writeFileSync(new URL('../public/mascot-bot.json', import.meta.url), `${JSON.stringify(definition, null, 2)}\n`);
console.log('definition', definition.body.path.length, 'B · scale', K.toFixed(4), '·', subpaths, 'subpaths');
